def add_country(data, **kwargs):  # функция добавляет страну в словарь
    country = kwargs["country"]  # получаю страну
    capital = kwargs["capital"]  # получаю столицу
    data[country] = capital  # записываю в словарь
    print("Файл сохранен")  # вывожу сообщение как в примере


def delete_country(data, country):  # функция удаляет страну
    if country in data:  # если страна есть
        del data[country]  # удаляю страну
        print("Данные удалены")  # сообщаю об удалении
    else:  # если страны нет
        print("Такой страны нет")  # сообщаю об ошибке


def find_country(data, country):  # функция ищет страну
    if country in data:  # если страна есть
        print(country, "-", data[country])  # показываю страну и столицу
    else:  # если страны нет
        print("Такой страны нет")  # сообщаю что не найдено


def edit_country(data, country, new_capital):  # функция меняет столицу
    if country in data:  # если страна есть
        data[country] = new_capital  # меняю столицу
        print("Данные обновлены")  # сообщаю об изменении
    else:  # если страны нет
        print("Такой страны нет")  # сообщаю об ошибке


def show_data(data):  # функция показывает весь словарь
    print(data)  # вывожу словарь


def show_menu():  # функция показывает меню
    print("*" * 30)  # верхняя линия
    print("Выбор действия:")  # заголовок
    print("1 - добавление данных")  # первый пункт
    print("2 - удаление данных")  # второй пункт
    print("3 - поиск данных")  # третий пункт
    print("4 - редактирование данных")  # четвертый пункт
    print("5 - просмотр данных")  # пятый пункт
    print("6 - завершение работы")  # шестой пункт


countries = {}  # создаю пустой словарь

show_menu()  # показываю меню
print("Ввод: 1")  # показываю выбранное действие
print("Введите название страны (С заглавной буквы): Россия")  # показываю ввод страны
print("Введите название столицы страны (с заглавной буквы): Москва")  # показываю ввод столицы
add_country(countries, **{"country": "Россия", "capital": "Москва"})  # добавляю данные через распаковку словаря

show_menu()  # снова показываю меню
print("Ввод: 5")  # показываю выбранное действие
show_data(countries)  # показываю словарь
